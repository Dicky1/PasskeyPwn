/**
 * markdown-writer.ts
 * 
 * Generates human-readable Markdown reports from PasskeyPwn findings.
 */

import { writeFileSync } from 'node:fs';
import { SarifReport } from './sarif-writer.js';

export interface TestMatrixRow {
  module: string;
  name: string;
  ceremony: string;
  classification: string;
  applicable: boolean;
  isFinding: boolean;
  statusCode: number | null;
  detail: string | null;
}

function matrixVerdict(r: TestMatrixRow): string {
  if (r.isFinding) return '🔴 FINDING';
  switch (r.classification) {
    case 'REJECTED':
      return '✅ rejected (secure)';
    case 'ACCEPTED':
      return '🔴 accepted';
    case 'ERROR':
      return '⚠️ error';
    case 'SKIPPED':
      return r.applicable ? '⏭ skipped' : '➖ N/A';
    default:
      return r.classification;
  }
}

function firstLine(s: string | null, max = 120): string {
  if (!s) return '';
  const line = s.split('\n')[0]!.trim();
  return line.length > max ? line.slice(0, max) + '…' : line;
}

/**
 * Generate a Markdown report from findings, optionally with a full test matrix.
 */
export function writeMarkdownReport(report: SarifReport, outputPath: string, matrix?: TestMatrixRow[]): void {
  const lines: string[] = [];

  lines.push('# PasskeyPwn — Security Test Report');
  lines.push('');
  lines.push(`**Target:** ${report.targetUrl}`);
  lines.push(`**Start:** ${report.startTime}`);
  lines.push(`**End:** ${report.endTime ?? new Date().toISOString()}`);
  lines.push(`**Findings:** ${report.findings.length}`);
  lines.push('');
  lines.push('---');
  lines.push('');

  // Summary table
  const errorCount = report.findings.filter(f => f.level === 'error').length;
  const warningCount = report.findings.filter(f => f.level === 'warning').length;
  const noteCount = report.findings.filter(f => f.level === 'note').length;

  lines.push('## Summary');
  lines.push('');
  lines.push('| Severity | Count |');
  lines.push('|----------|-------|');
  lines.push(`| 🔴 Error (High) | ${errorCount} |`);
  lines.push(`| 🟡 Warning (Medium) | ${warningCount} |`);
  lines.push(`| 🔵 Note (Low) | ${noteCount} |`);
  lines.push('');

  if (report.findings.length === 0) {
    lines.push('> ✅ No findings. All applicable WebAuthn validations appear to be properly enforced.');
    lines.push('');
  }

  // Test matrix: everything that was exercised, not just findings.
  if (matrix && matrix.length > 0) {
    lines.push('## Test Matrix');
    lines.push('');
    lines.push('| # | Module | Ceremony | Verdict | HTTP | Server response |');
    lines.push('|---|--------|----------|---------|------|-----------------|');
    matrix.forEach((r, i) => {
      lines.push(
        `| ${i + 1} | \`${r.module}\` | ${r.ceremony} | ${matrixVerdict(r)} | ${r.statusCode ?? '—'} | ${firstLine(r.detail).replace(/\|/g, '\\|')} |`,
      );
    });
    lines.push('');
    lines.push(
      '> A "rejected (secure)" verdict means the relying party correctly refused the mutated ceremony. ' +
        'A "FINDING" means it accepted something it should have rejected.',
    );
    lines.push('');
  }

  // Detailed findings
  if (report.findings.length > 0) {
    lines.push('## Findings');
    lines.push('');

    for (let i = 0; i < report.findings.length; i++) {
      const f = report.findings[i]!;
      const icon = f.level === 'error' ? '🔴' : f.level === 'warning' ? '🟡' : '🔵';

      lines.push(`### ${icon} ${i + 1}. ${f.ruleName}`);
      lines.push('');
      lines.push(`- **Rule ID:** \`${f.ruleId}\``);
      lines.push(`- **Severity:** ${f.level}`);
      lines.push(`- **Category:** ${f.category}`);
      lines.push(`- **Endpoint:** \`${f.endpoint}\``);
      lines.push('');
      lines.push(f.message);
      lines.push('');

      if (f.payload) {
        lines.push('**Payload:**');
        lines.push('```');
        lines.push(f.payload);
        lines.push('```');
        lines.push('');
      }

      if (f.responseExcerpt) {
        lines.push('**Server Response:**');
        lines.push('```');
        lines.push(f.responseExcerpt.substring(0, 500));
        lines.push('```');
        lines.push('');
      }

      if (f.statusCode) {
        lines.push(`**HTTP Status:** ${f.statusCode}`);
        lines.push('');
      }

      lines.push('---');
      lines.push('');
    }
  }

  lines.push('');
  lines.push('*Generated by PasskeyPwn v1.0.0*');

  writeFileSync(outputPath, lines.join('\n'), 'utf-8');
  console.log(`[report] Markdown report written to: ${outputPath}`);
}

