/**
 * html-writer.ts — Self-contained HTML report for PasskeyPwn findings.
 */
import { writeFileSync } from 'node:fs';
import { SarifReport } from './sarif-writer.js';

export function writeHtmlReport(report: SarifReport, outputPath: string, matrix?: { module: string; name: string; ceremony: string; classification: string; applicable: boolean; isFinding: boolean; statusCode: number | null; detail: string | null }[]): void {
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const findings = report.findings;
  const rows = (matrix ?? []).map((r, i) =>
    `<tr class="${r.isFinding ? 'finding' : ''}"><td>${i + 1}</td><td><code>${esc(r.module)}</code></td><td>${esc(r.ceremony)}</td><td>${r.isFinding ? '🔴 FINDING' : esc(r.classification)}</td><td>${r.statusCode ?? '—'}</td><td>${esc((r.detail ?? '').slice(0, 120))}</td></tr>`
  ).join('');
  const detailBlocks = findings.map((f, i) => `
    <section class="finding">
      <h3>${i + 1}. ${esc(f.ruleName)} <span class="sev ${f.level}">${esc(f.level)}</span></h3>
      <p><b>Rule:</b> <code>${esc(f.ruleId)}</code> · <b>Category:</b> ${esc(f.category)} · <b>Endpoint:</b> <code>${esc(f.endpoint)}</code></p>
      <p>${esc(f.message)}</p>
      ${f.payload ? `<pre>${esc(f.payload)}</pre>` : ''}
      ${f.responseExcerpt ? `<pre>${esc(f.responseExcerpt.slice(0, 500))}</pre>` : ''}
      ${f.statusCode ? `<p>HTTP ${f.statusCode}</p>` : ''}
    </section>`).join('');

  const html = `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8"><title>PasskeyPwn Report</title>
<style>
body{font-family:system-ui,sans-serif;margin:2rem;color:#222}
table{border-collapse:collapse;width:100%}th,td{border:1px solid #ddd;padding:6px}tr.finding{background:#fdecea}
.sev{padding:2px 6px;border-radius:4px;color:#fff;font-size:12px}
.sev.error{background:#c0392b}.sev.warning{background:#e67e22}.sev.note{background:#2980b9}
pre{background:#f4f4f4;padding:8px;overflow:auto}
</style></head><body>
<h1>PasskeyPwn — Security Test Report</h1>
<p><b>Target:</b> ${esc(report.targetUrl)} · <b>Findings:</b> ${findings.length}</p>
<h2>Test Matrix</h2>
<table><thead><tr><th>#</th><th>Module</th><th>Ceremony</th><th>Verdict</th><th>HTTP</th><th>Response</th></tr></thead><tbody>${rows}</tbody></table>
<h2>Findings</h2>
${detailBlocks || '<p>✅ No findings.</p>'}
<p><em>Generated by PasskeyPwn v1.0.0</em></p>
</body></html>`;
  writeFileSync(outputPath, html, 'utf-8');
  console.log(`[report] HTML report written to: ${outputPath}`);
}